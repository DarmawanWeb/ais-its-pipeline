-- 0004_outbox_per_key — upgrades the outbox of 0003 (kit 0.2 DDL) for the
-- per-key relay of @darmawanweb/ais-its-nest 0.3 (spec §7.1, §13.2).
--
-- Adds `seq` (insertion order, numbered in the 0.2 relay order for rows
-- already there) and `next_attempt_at` (retry time of a failed row) with
-- their indexes. The relay then runs on every replica (FOR UPDATE SKIP
-- LOCKED) and publishes the events of up to OUTBOX_PUBLISH_CONCURRENCY
-- vessels (entity_key = MMSI) at once, each vessel's events in order; a
-- failing vessel backs off alone instead of blocking every vessel behind
-- it. During a rolling upgrade a 0.2 processor still relays this table
-- (serial mode), never at the same time as a 0.3 one (exclusive versus
-- shared advisory lock).
--
-- Runs in one transaction and locks the table until it commits (writers
-- of position batches wait). Published rows are only kept for diagnostics
-- (10 minutes, OUTBOX_RETENTION_MINUTES; the events stay in AIS_POSITION),
-- so they are deleted first: the `seq` backfill then rewrites the pending
-- rows only, normally a handful. Everything after the DELETE is
-- outboxUpgradeSql() of @darmawanweb/ais-its-nest 0.3.0, generated with
--   node -e "import('@darmawanweb/ais-its-nest/nats').then((m) => console.log(m.outboxUpgradeSql()))"
-- and idempotent (a table that already has the columns is left as is).

DELETE FROM "outbox" WHERE published_at IS NOT NULL;

ALTER TABLE "outbox" ADD COLUMN IF NOT EXISTS next_attempt_at timestamptz;
DO $outbox_upgrade$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_attribute WHERE attrelid = to_regclass('"outbox"')
      AND attname = 'seq' AND attnum > 0 AND NOT attisdropped
  ) THEN
    ALTER TABLE "outbox" ADD COLUMN seq bigint;
    UPDATE "outbox" AS o SET seq = r.rn
      FROM (SELECT id, row_number() OVER (ORDER BY created_at, id) AS rn FROM "outbox") AS r
     WHERE o.id = r.id;
    ALTER TABLE "outbox" ALTER COLUMN seq SET NOT NULL;
    ALTER TABLE "outbox" ALTER COLUMN seq ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(pg_get_serial_sequence('"outbox"', 'seq'),
      (SELECT coalesce(max(seq), 0) + 1 FROM "outbox"), false);
    ALTER TABLE "outbox" ADD CONSTRAINT "outbox_seq_key" UNIQUE (seq);
  END IF;
END
$outbox_upgrade$;
CREATE INDEX IF NOT EXISTS "outbox_pending_idx" ON "outbox" (created_at, id)
  WHERE published_at IS NULL AND failed_at IS NULL;
CREATE INDEX IF NOT EXISTS "outbox_pending_seq_idx" ON "outbox" (seq)
  WHERE published_at IS NULL AND failed_at IS NULL;
CREATE INDEX IF NOT EXISTS "outbox_pending_key_idx" ON "outbox" (entity_key, seq)
  WHERE published_at IS NULL AND failed_at IS NULL;
CREATE INDEX IF NOT EXISTS "outbox_retry_idx" ON "outbox" (entity_key, seq)
  WHERE published_at IS NULL AND failed_at IS NULL AND next_attempt_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS "outbox_failed_idx" ON "outbox" (failed_at)
  WHERE failed_at IS NOT NULL;
